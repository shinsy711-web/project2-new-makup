export type RegionData = {
  /** 레지스트리 path 와 동일 */
  path: string;
  /** 지역명 (본문용) */
  name: string;
  /** 폼 기본 선택 지역 (data/constants REGIONS 값) */
  formRegion: string;
  /** 학원이 몰린 상권 */
  areas: string[];
  /** 통학 가능 범위 */
  commute: string;
  /** 자격증반 수강료 범위 */
  tuition: string;
  /** 원데이클래스 가격대 */
  oneday: string;
  /** 개강 주기 */
  openCycle: string;
  /** 이 지역의 성격 한 문장 */
  character: string;
  /** 지역 특징 3~4개 */
  highlights: string[];
  /** 주요 취업처 */
  jobs: string;
  /** 국비 과정 개설 정도 */
  funding: string;
  /** 인접 지역 페이지 경로 */
  nearby: string[];
  /** 이 지역에서 특히 수요가 있는 분야 페이지 */
  fields: string[];
};

